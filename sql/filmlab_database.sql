-- Đồng bộ sequence sau khi chèn ID mẫu tường minh.
DO $$
DECLARE
    identity_column RECORD;
    sequence_name TEXT;
BEGIN
    FOR identity_column IN
        SELECT table_schema, table_name, column_name
        FROM information_schema.columns
        WHERE table_schema = 'public' AND is_identity = 'YES'
    LOOP
        sequence_name := pg_get_serial_sequence(
            format('%I.%I', identity_column.table_schema, identity_column.table_name),
            identity_column.column_name
        );
        EXECUTE format(
            'SELECT setval(%L, COALESCE(MAX(%I), 0) + 1, false) FROM %I.%I',
            sequence_name,
            identity_column.column_name,
            identity_column.table_schema,
            identity_column.table_name
        );
    END LOOP;
END $$;

COMMIT;

-- Example: calculate order subtotal and total from snapshot prices
SELECT o.order_code,
       SUM(oi.quantity * oi.unit_price) AS subtotal,
       SUM(oi.quantity * oi.unit_price) + o.delivery_fee - o.discount_amount AS total_amount
FROM orders o
JOIN order_items oi ON oi.order_id = o.order_id
GROUP BY o.order_id, o.order_code, o.delivery_fee, o.discount_amount;
